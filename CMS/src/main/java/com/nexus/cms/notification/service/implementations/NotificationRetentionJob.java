package com.nexus.cms.notification.service.implementations;

import com.nexus.cms.notification.entities.Notification;
import com.nexus.cms.notification.entities.NotificationFailure;
import com.nexus.cms.notification.entities.NotificationReadReceipt;
import com.nexus.cms.notification.properties.NotificationProperties;
import com.nexus.cms.notification.repositories.NotificationFailureRepo;
import com.nexus.cms.notification.repositories.NotificationReadReceiptRepo;
import com.nexus.cms.notification.repositories.NotificationRepo;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.List;

/**
 * Removes notifications that are older than the retention window.
 * <p>
 * The window is set by {@code notification.retention.days}. A value of zero
 * disables the cleanup; a negative value keeps notifications forever.
 * <p>
 * Read receipts are removed first. The schema is generated by Hibernate, which
 * does not add a cascading delete to the foreign key, so the receipts have to
 * go first or the notifications could not be deleted.
 */
@Service
@RequiredArgsConstructor
@Slf4j
public class NotificationRetentionJob {

    private final NotificationRepo notificationRepo;
    private final NotificationReadReceiptRepo readReceiptRepo;
    private final NotificationFailureRepo failureRepo;
    private final NotificationProperties properties;

    /**
     * Runs shortly after midnight.
     */
    @Scheduled(cron = "0 15 3 * * *")
    @Transactional
    public void purgeExpiredNotifications() {
        int retentionDays = properties.getRetentionDays();
        if (retentionDays == 0) {
            log.debug("Notification retention is disabled — nothing to purge");
            return;
        }
        if (retentionDays < 0) {
            log.debug("Notification retention is set to keep everything — nothing to purge");
            return;
        }

        Instant cutoffInstant = Instant.now().minusSeconds(retentionDays * 86400L);
        Timestamp cutoff = Timestamp.from(cutoffInstant);
        try {
            List<Notification> expired = notificationRepo.findCreatedBefore(cutoff);
            if (!expired.isEmpty()) {
                List<Long> expiredIds = expired.stream().map(Notification::getNotificationId).toList();
                List<NotificationReadReceipt> receipts = readReceiptRepo.findByNotificationIds(expiredIds);
                if (!receipts.isEmpty()) {
                    readReceiptRepo.deleteAll(receipts);
                }
                notificationRepo.deleteAll(expired);
                log.info("Purged {} notifications and {} read receipts older than {} days",
                        expired.size(), receipts.size(), retentionDays);
            }
        } catch (Exception e) {
            log.error("Failed to purge expired notifications", e);
        }
    }

    /**
     * Removes recorded failures that are older than the failure retention
     * window.
     */
    @Scheduled(cron = "0 45 3 * * *")
    @Transactional
    public void purgeExpiredFailures() {
        int retentionDays = properties.getDlqFailureRetentionDays();
        if (retentionDays <= 0) {
            return;
        }
        Instant cutoff = Instant.now().minusSeconds(retentionDays * 86400L);
        try {
            List<NotificationFailure> expired = failureRepo.findCreatedBefore(cutoff);
            if (!expired.isEmpty()) {
                failureRepo.deleteAll(expired);
                log.info("Purged {} recorded failures older than {} days", expired.size(), retentionDays);
            }
        } catch (Exception e) {
            log.error("Failed to purge expired notification failures", e);
        }
    }
}
