package com.nexus.cms.notification.repositories;

import com.nexus.cms.notification.entities.NotificationReadReceipt;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;

import java.util.List;

public interface NotificationReadReceiptRepo extends JpaRepository<NotificationReadReceipt, Long> {

    /**
     * Whether a user has already read a notification.
     */
    boolean existsByNotificationNotificationIdAndUserId(Long notificationId, Long userId);

    /**
     * The read receipts a user holds, used to work out which notifications are
     * still unread.
     */
    @Query("SELECT r.notification.notificationId FROM NotificationReadReceipt r WHERE r.userId = :userId")
    List<Long> findReadNotificationIdsForUser(@Param("userId") Long userId);

    /**
     * Delete every receipt for a set of notifications. Used by the retention
     * job, which removes the receipts before the notifications themselves
     * because the schema is generated by Hibernate and carries no cascading
     * delete.
     */
    @Query("SELECT r FROM NotificationReadReceipt r WHERE r.notification.notificationId IN :notificationIds")
    List<NotificationReadReceipt> findByNotificationIds(@Param("notificationIds") List<Long> notificationIds);
}
